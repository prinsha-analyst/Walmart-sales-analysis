SELECT 
    category,
    SUM(total) AS revenue
FROM walmart
GROUP BY category
HAVING SUM(total) < (
        SELECT AVG(category_revenue)
        FROM(
            SELECT SUM(total) AS category_revenue
            FROM walmart
            GROUP BY category
        ) t
);

