-- Q.8 Categorise sales into 3 group MORNING, AFTERNOON, EVENING. Find out each of the shift and number of invoices
SELECT branch,
CASE
    WHEN EXTRACT(HOUR FROM CAST(time AS TIME)) < 12 THEN 'Morning'
    WHEN EXTRACT(HOUR FROM CAST(time AS TIME)) BETWEEN 12 AND 17 THEN 'Afternoon'
    ELSE 'Evening'
END AS day_time,
COUNT(*)
FROM walmart
GROUP BY 1,2
order by 1,3 desc;	 

-- Q.9 Identify 5 branch with highest decrease ratio in revenue compare to last year(current year 2023 and last year 2022)
 
 with revenue_2022 as 
	 (select branch,
		sum(total) as revenue
	from walmart
	WHERE extract(YEAR FROM STR_TO_DATE(date, '%d/%m/%y')) = 2022
	group by 1
		),
revenue_2023 as 
(select branch,
		sum(total) as revenue
from walmart
WHERE extract(YEAR FROM STR_TO_DATE(date, '%d/%m/%y')) = 2023
group by 1
		)
select 
	ls.branch,
    ls.revenue as last_year_revenue,
    cs.revenue as current_year_revenue,
    round(
		(ls.revenue - cs.revenue) / ls.revenue* 100 ,2
        ) as decreased_revenue_ratio
from revenue_2022 as ls
Join revenue_2023 as cs
on ls.branch = cs.branch
where ls.revenue > cs.revenue
order by 4 desc
limit 5;

